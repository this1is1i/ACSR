def mk_obsidian_link(q_id):
    """生成 Obsidian 兼容的 wikilink: [[file#^anchor|QN]]"""
    fname = QA_FILE.get(q_id, "")
    if not fname:
        return q_id
    anchor = 'q5-ask' if '追问' in q_id else q_id.lower()
    return f'[[{fname}#^{anchor}|{q_id}]]'


# ── 处理单个文件 ────────────────────────────────────────────────────────
HEADING_RE = re.compile(r'^(#{1,6}\s+)(Q\d+(?:追问)?)([：:]\s*.+)$')
META_LINE_RE = re.compile(r'^\*\*(?:标签|关联)\*\*:')

def process_file(filepath):
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    lines = content.split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m = HEADING_RE.match(line.strip())
        if m:
            prefix = m.group(1)
            q_id = m.group(2)
            rest = m.group(3)
            anchor = 'q5-ask' if '追问' in q_id else q_id.lower()

            # 写入标题行（追加 ^anchor，幂等：检查是否已有）
            if line.rstrip().endswith(f'^{anchor}'):
                out.append(line)
            else:
                # 去掉旧的 ^ 锚点（如果有误加的）
                clean = re.sub(r'\s*\^[a-zA-Z0-9_-]+\s*$', '', line.rstrip())
                out.append(f'{clean} ^{anchor}')

            # 写入元数据（幂等：跳过紧随的已有元数据行）
            tags, related = meta_for(q_id, rest)
            i += 1
            # 跳过已有的空行和元数据行
            while i < len(lines) and (lines[i].strip() == '' or META_LINE_RE.match(lines[i].strip())):
                i += 1
            # 插入元数据
            out.append("")
            out.append(f'**标签**: {" ".join(tags)}')
            out.append(f'**关联**: {", ".join(mk_obsidian_link(r) for r in related)}')
            out.append("")
            # 当前行（跳过空白元数据后的正文首行）尚未写入，继续循环
            continue

        out.append(line)
        i += 1

    with open(filepath, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"  OK {os.path.basename(filepath)}")


