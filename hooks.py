# 也匹配 Q5追问 等特殊形式
# 保持原始 Q# 查询不变，特殊形式在 wikilink 中不带后缀
WIKILINK_RE = re.compile(r'\[\[(Q\d+(?:追问)?)\]\]')


def _mkdocs_anchor(heading_text):
    """模拟 MkDocs 的 anchor 生成规则：全小写，非字母数字变连字符"""
    # 取冒号前的主标题部分（去除日期和 git hash）
    text = heading_text.strip().lower()
    # 将中文标点和空格替换为连字符
    anchor = re.sub(r'[^\w一-鿿-]', '', text.replace(' ', '-').replace('：', '-').replace(':', '-').replace('（', '-').replace('）', '-'))
    # 处理中间的连字符
    anchor = re.sub(r'-+', '-', anchor).strip('-')
    return anchor


def on_page_markdown(markdown, page, config, files):
    """
    MkDocs 钩子：页面 markdown 渲染前，将 [[Q42]] 转换为标准链接。
    """
    def replace_wikilink(match):
        q_id = match.group(1)
        if q_id in QA_FILE_MAP:
            target_file, anchor = QA_FILE_MAP[q_id]
            # 计算正确的相对路径
            return f'[{q_id}]({target_file}#{anchor})'
        # 未匹配的保持原样
        return match.group(0)

    return WIKILINK_RE.sub(replace_wikilink, markdown)


def on_page_content(html, page, config, files):
    """
    可选：对生成的 HTML 做后处理。
    """
    return html
